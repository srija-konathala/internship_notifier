#!/usr/bin/env python3
"""
Find high-performing London startups and put their job boards under watch.

Seeds come from three places: the YC open dataset filtered to London, London VC
portfolio pages, and the hand-curated list in data/uk_seed_companies.json. Each
candidate is resolved to a real job board (scripts/uk_ats_resolve.py), verified
to have live UK postings, scored, and — if it clears the threshold — appended to
config.uk.auto.json, which main.py merges on top of config.json.

Everything seen is remembered in data/uk_startups.json, including companies we
could not resolve, so each run can retry them and measure hiring velocity
(change in open-role count) between runs.

Usage:
    python scripts/discover_uk_startups.py                      # full run
    python scripts/discover_uk_startups.py --rank 20            # leaderboard
    python scripts/discover_uk_startups.py --company Suna --domain suna.health
    python scripts/discover_uk_startups.py --dry-run --limit 20
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

import requests

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import main as watcher  # noqa: E402
import uk_ats_resolve as resolver  # noqa: E402

DATA_DIR = ROOT / "data"
REGISTRY_PATH = DATA_DIR / "uk_startups.json"
SEED_PATH = DATA_DIR / "uk_seed_companies.json"
AUTO_CONFIG_PATH = ROOT / "config.uk.auto.json"
CONFIG_PATH = ROOT / "config.json"

YC_API = "https://yc-oss.github.io/api/companies/all.json"

# Portfolio pages that serve company links in plain HTML. Ones that render
# client-side are skipped rather than special-cased.
VC_PORTFOLIOS = {
    "seedcamp": "https://seedcamp.com/companies/",
    "octopus": "https://octopusventures.com/portfolio/",
    "concept": "https://www.conceptventures.vc/portfolio",
    "ada": "https://adaventures.com/portfolio/",
    "hoxton": "https://www.hoxtonventures.com/portfolio",
}

VC_LINK_SKIP = re.compile(
    r"(twitter|x\.com|linkedin|facebook|instagram|youtube|medium|crunchbase|github|"
    r"google|apple|mailto|cookiebot|hotjar|typeform|intellimize|jsdelivr|cloudflare|"
    r"fontawesome|website-files|wp-content|\.pdf|\.png|\.jpg|\.svg)",
    re.I,
)

ENGINEERING_RE = re.compile(
    r"engineer|developer|software|data|machine learning|research|scientist|infra|platform",
    re.I,
)
EARLY_CAREER_KEYWORDS = [
    "intern", "internship", "placement", "graduate", "junior", "student",
    "apprentice", "trainee", "entry level", "new grad",
]

UA = {"User-Agent": resolver.UA}


# --------------------------------------------------------------------------
# registry
# --------------------------------------------------------------------------
def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def load_registry() -> dict[str, Any]:
    if REGISTRY_PATH.is_file():
        try:
            return json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            print(f"[warn] {REGISTRY_PATH} unreadable; starting a new registry")
    return {"updated_at": 0, "companies": {}}


def save_registry(registry: dict[str, Any]) -> None:
    DATA_DIR.mkdir(exist_ok=True)
    registry["updated_at"] = int(time.time())
    REGISTRY_PATH.write_text(json.dumps(registry, indent=1) + "\n", encoding="utf-8")


def load_auto_config() -> dict[str, Any]:
    if AUTO_CONFIG_PATH.is_file():
        try:
            return json.loads(AUTO_CONFIG_PATH.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            pass
    return {
        "_comment": "Generated by scripts/discover_uk_startups.py; main.py merges "
                    "these on top of config.json. Safe to prune by hand.",
        "sources": [],
    }


# --------------------------------------------------------------------------
# seeds
# --------------------------------------------------------------------------
def seeds_from_yc() -> list[dict[str, Any]]:
    """YC's open dataset, filtered to companies with a London location."""
    try:
        r = requests.get(YC_API, headers=UA, timeout=60)
        r.raise_for_status()
        companies = r.json()
    except Exception as e:
        print(f"[warn] YC dataset unavailable: {e}")
        return []

    out = []
    for c in companies:
        locations = f"{c.get('all_locations') or ''} {c.get('regions') or ''}".lower()
        if "london" not in locations and "united kingdom" not in locations:
            continue
        if c.get("status") != "Active":
            continue
        website = (c.get("website") or "").strip()
        out.append(
            {
                "name": c.get("name") or "",
                "domain": re.sub(r"^https?://(www\.)?", "", website).strip("/"),
                "seed_source": "yc",
                "yc": {
                    "batch": c.get("batch"),
                    "stage": c.get("stage"),
                    "team_size": c.get("team_size"),
                    "top_company": bool(c.get("top_company")),
                    "is_hiring": bool(c.get("isHiring")),
                    "industry": c.get("industry"),
                },
            }
        )
    print(f"YC seeds (London, active): {len(out)}")
    return out


def seeds_from_vc() -> list[dict[str, Any]]:
    """Portfolio companies of London-focused funds — a decent quality prior."""
    out: list[dict[str, Any]] = []
    for fund, url in VC_PORTFOLIOS.items():
        try:
            r = requests.get(url, headers=UA, timeout=30)
            if r.status_code != 200:
                print(f"[warn] {fund} portfolio returned {r.status_code}")
                continue
        except Exception as e:
            print(f"[warn] {fund} portfolio unavailable: {e}")
            continue
        own = re.sub(r"^https?://(www\.)?", "", url).split("/")[0]
        hosts: set[str] = set()
        for link in re.findall(r'href="(https?://[^"]+)"', r.text):
            if VC_LINK_SKIP.search(link):
                continue
            host = link.split("/")[2].lower().removeprefix("www.")
            if host == own or host.endswith(own) or host.count(".") > 2:
                continue
            hosts.add(host)
        for host in hosts:
            name = host.split(".")[0].replace("-", " ").title()
            out.append({"name": name, "domain": host, "seed_source": f"vc:{fund}"})
        print(f"{fund} portfolio seeds: {len(hosts)}")
    return out


def seeds_from_curated() -> list[dict[str, Any]]:
    if not SEED_PATH.is_file():
        return []
    data = json.loads(SEED_PATH.read_text(encoding="utf-8"))
    out = []
    for entry in data.get("companies") or []:
        out.append(
            {
                "name": entry.get("name") or "",
                "domain": (entry.get("domain") or "").strip(),
                "seed_source": "curated",
                "note": entry.get("note"),
            }
        )
    print(f"Curated seeds: {len(out)}")
    return out


def existing_source_keys() -> tuple[set[str], set[str]]:
    """Source keys and company names already watched, so we never duplicate."""
    keys: set[str] = set()
    names: set[str] = set()
    for path in (CONFIG_PATH, AUTO_CONFIG_PATH):
        if not path.is_file():
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        for src in data.get("sources") or []:
            keys.add(watcher.source_key(src))
            names.add(slugify(src.get("name") or ""))
    return keys, names


# --------------------------------------------------------------------------
# scoring
# --------------------------------------------------------------------------
def score_candidate(entry: dict[str, Any], result: dict[str, Any]) -> tuple[int, dict[str, Any]]:
    """
    Rough "is this a high performing London startup worth watching" score.
    Everything here is a free signal; nothing needs a paid data provider.
    """
    signals: dict[str, Any] = {}
    score = 0.0

    seed = entry.get("seed_source") or ""
    if seed == "yc":
        score += 15
    elif seed.startswith("vc:"):
        score += 12
    elif seed in ("curated", "manual"):
        score += 10
    signals["backing"] = seed

    yc = entry.get("yc") or {}
    batch = str(yc.get("batch") or "")
    year = re.search(r"(20\d{2})", batch)
    if year:
        age = 2026 - int(year.group(1))
        recency = 12 if age <= 2 else (8 if age <= 4 else 3)
        score += recency
        signals["batch"] = batch
    if yc.get("top_company"):
        score += 8
        signals["yc_top_company"] = True
    if yc.get("stage") == "Growth":
        score += 6
        signals["stage"] = "Growth"

    team = yc.get("team_size")
    if isinstance(team, int) and team > 0:
        if 20 <= team <= 250:
            score += 12
        elif 10 <= team < 20 or 250 < team <= 600:
            score += 8
        else:
            score += 4
        signals["team_size"] = team

    open_roles = result.get("jobs") or 0
    score += min(18.0, 6 * math.log10(open_roles + 1) * 2)
    signals["open_roles"] = open_roles

    uk_jobs = result.get("uk_jobs") or 0
    if uk_jobs:
        score += min(10.0, 3 * math.log10(uk_jobs + 1) * 2)
    signals["uk_roles"] = uk_jobs

    history = entry.get("history") or []
    if history:
        previous = history[-1].get("jobs") or 0
        delta = open_roles - previous
        signals["role_delta"] = delta
        if delta > 0:
            score += min(20.0, delta * 2.5)
        elif delta < 0:
            score -= min(8.0, abs(delta))

    eng = result.get("engineering_roles") or 0
    if open_roles:
        share = eng / open_roles
        score += 10 * share
        signals["engineering_share"] = round(share, 2)

    early = result.get("uk_early_career") or 0
    if early:
        score += min(15.0, 5 * early)
    signals["early_career_roles"] = early

    return int(max(0, min(100, round(score)))), signals


# --------------------------------------------------------------------------
# discovery
# --------------------------------------------------------------------------
def enrich(result: dict[str, Any]) -> dict[str, Any]:
    """Add engineering-role counts to a resolver result."""
    source = result["source"]
    jobs, err = watcher.fetch_source(source)
    if err:
        return result
    result["engineering_roles"] = sum(1 for j in jobs if ENGINEERING_RE.search(j["title"]))
    return result


def process(entry: dict[str, Any], render: bool) -> dict[str, Any]:
    name = entry["name"]
    domain = entry.get("domain") or None
    try:
        result = resolver.resolve(name, domain, render=render, require_uk=False)
    except Exception as e:
        return {**entry, "status": "error", "error": str(e)[:120]}

    if not result:
        return {**entry, "status": "unresolved"}
    if not result.get("uk_verified"):
        return {**entry, "status": "no_uk_postings", "result": result}
    return {**entry, "status": "resolved", "result": enrich(result)}


def to_source(entry: dict[str, Any], result: dict[str, Any]) -> dict[str, Any]:
    src = dict(result["source"])
    src["name"] = entry["name"]
    src["countries"] = ["GB"]
    src["role_profile"] = "startup"
    src["keyword_profile"] = "startup_early_career"
    src["discovered"] = {
        "at": int(time.time()),
        "seed_source": entry.get("seed_source"),
        "score": entry.get("score"),
        "uk_roles": result.get("uk_jobs"),
    }
    return src


def run_discovery(args: argparse.Namespace) -> dict[str, Any]:
    registry = load_registry()
    companies = registry.setdefault("companies", {})
    known_keys, known_names = existing_source_keys()

    if args.company:
        seeds = [{"name": args.company, "domain": args.domain, "seed_source": "manual"}]
    else:
        seeds = []
        if "curated" in args.seeds:
            seeds += seeds_from_curated()
        if "yc" in args.seeds:
            seeds += seeds_from_yc()
        if "vc" in args.seeds:
            seeds += seeds_from_vc()

    # Deduplicate, then prefer companies we have never resolved and ones we are
    # already watching (so their history and score stay current).
    queue: dict[str, dict[str, Any]] = {}
    for seed in seeds:
        if not seed.get("name"):
            continue
        slug = slugify(seed["name"])
        if not slug:
            continue
        stored = companies.get(slug) or {}
        merged = {**stored, **{k: v for k, v in seed.items() if v}}
        merged.setdefault("first_seen", int(time.time()))
        if slug in queue:
            continue
        if stored.get("status") == "rejected" and not args.recheck_rejected:
            continue
        queue[slug] = merged

    # Refresh what we already watch (keeps hiring velocity current), then try
    # candidates we have never touched, then retry stale unresolved ones oldest
    # first so a daily run works through the backlog instead of restarting at A.
    def priority(item: tuple[str, dict[str, Any]]) -> tuple[int, float, str]:
        slug, entry = item
        status = entry.get("status")
        if status == "watching":
            group = 0
        elif not status:
            group = 1
        else:
            group = 2
        return group, entry.get("last_checked") or 0, slug

    ordered = sorted(queue.items(), key=priority)
    if args.limit:
        ordered = ordered[: args.limit]

    print(f"Resolving {len(ordered)} candidate(s)...")
    results: list[tuple[str, dict[str, Any]]] = []
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = {
            pool.submit(process, entry, args.render): slug for slug, entry in ordered
        }
        for future in futures:
            slug = futures[future]
            try:
                results.append((slug, future.result()))
            except Exception as e:
                print(f"[warn] {slug}: {e}")

    added: list[dict[str, Any]] = []
    auto = load_auto_config()
    auto_sources = auto.setdefault("sources", [])

    for slug, outcome in sorted(results):
        entry = companies.setdefault(slug, {})
        entry.update({k: v for k, v in outcome.items() if k not in ("result",)})
        entry["last_checked"] = int(time.time())
        result = outcome.get("result")

        if outcome["status"] != "resolved" or not result:
            entry.setdefault("score", 0)
            continue

        score, signals = score_candidate(entry, result)
        entry["score"] = score
        entry["signals"] = signals
        entry["board"] = result["source"]
        entry["sample_roles"] = result.get("sample") or []
        history = entry.setdefault("history", [])
        history.append(
            {
                "ts": int(time.time()),
                "jobs": result.get("jobs"),
                "uk_jobs": result.get("uk_jobs"),
                "uk_early_career": result.get("uk_early_career"),
            }
        )
        del history[:-12]

        source = to_source(entry, result)
        key = watcher.source_key(source)
        if key in known_keys or slug in known_names:
            entry["status"] = "watching"
            continue
        if score < args.min_score:
            entry["status"] = "below_threshold"
            continue
        if len(added) >= args.max_add:
            entry["status"] = "queued"
            continue

        auto_sources.append(source)
        known_keys.add(key)
        known_names.add(slug)
        entry["status"] = "watching"
        added.append({"name": entry["name"], "score": score, "source": source,
                      "uk_roles": result.get("uk_jobs"), "sample": entry["sample_roles"]})

    if args.dry_run:
        print("\n[dry run] nothing written")
    else:
        save_registry(registry)
        AUTO_CONFIG_PATH.write_text(json.dumps(auto, indent=2) + "\n", encoding="utf-8")

    summary = {
        "checked": len(results),
        "added": added,
        "watching": sum(1 for c in companies.values() if c.get("status") == "watching"),
        "unresolved": sum(1 for c in companies.values() if c.get("status") == "unresolved"),
    }
    return summary


# --------------------------------------------------------------------------
# reporting
# --------------------------------------------------------------------------
def print_summary(summary: dict[str, Any]) -> None:
    print(
        f"\nChecked {summary['checked']} | added {len(summary['added'])} | "
        f"watching {summary['watching']} | unresolved {summary['unresolved']}"
    )
    for item in summary["added"]:
        src = item["source"]
        board = src.get("board_token") or src.get("board_slug") or src.get("company_slug") or src.get("tenant")
        print(f"  + {item['name']:28} score={item['score']:3} {src['type']}:{board} "
              f"({item['uk_roles']} UK roles)")
        for sample in (item.get("sample") or [])[:2]:
            print(f"      - {sample}")


def send_digest(summary: dict[str, Any]) -> None:
    token = watcher.get_env("TELEGRAM_BOT_TOKEN")
    chat_id = watcher.get_env("TELEGRAM_CHAT_ID")
    added = summary["added"]
    if not added:
        return
    lines = [f"<b>{len(added)} new London startup(s) under watch</b>", ""]
    for item in added:
        signals = f"score {item['score']}, {item['uk_roles']} UK roles"
        lines.append(f"{watcher.escape_html(item['name'])} — {signals}")
        for sample in (item.get("sample") or [])[:2]:
            lines.append(f"  · {watcher.escape_html(sample)}")
    watcher.telegram_send_html(token, chat_id, "\n".join(lines[:60]))


def print_ranking(limit: int) -> None:
    registry = load_registry()
    rows = [
        (c.get("score") or 0, slug, c)
        for slug, c in (registry.get("companies") or {}).items()
        if c.get("board")
    ]
    rows.sort(reverse=True)
    print(f"{'score':>5}  {'company':28} {'status':16} roles  signals")
    for score, slug, c in rows[:limit]:
        signals = c.get("signals") or {}
        bits = ", ".join(
            f"{k}={v}" for k, v in signals.items()
            if k in ("batch", "team_size", "role_delta", "early_career_roles", "stage")
        )
        print(f"{score:>5}  {c.get('name', slug)[:28]:28} {c.get('status', ''):16} "
              f"{signals.get('uk_roles', 0):>5}  {bits}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--seeds", default="curated,yc,vc",
                    help="Comma-separated seed sources: curated, yc, vc")
    ap.add_argument("--limit", type=int, default=80,
                    help="Max candidates to resolve this run")
    ap.add_argument("--max-add", type=int, default=25,
                    help="Max sources to add to config.uk.auto.json in one run")
    ap.add_argument("--min-score", type=int, default=45,
                    help="Score threshold for auto-adding a board")
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--render", action="store_true",
                    help="Allow the Playwright fallback for client-side careers pages")
    ap.add_argument("--recheck-rejected", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--digest", action="store_true", help="Send a Telegram digest")
    ap.add_argument("--company", help="Resolve a single company by name")
    ap.add_argument("--domain", help="Domain for --company")
    ap.add_argument("--rank", type=int, nargs="?", const=25,
                    help="Print the scored leaderboard and exit")
    args = ap.parse_args()

    if args.rank:
        print_ranking(args.rank)
        return

    args.seeds = {s.strip() for s in args.seeds.split(",") if s.strip()}
    if args.company:
        # An explicitly named company is a deliberate choice, not a guess.
        args.min_score = 0
        args.max_add = max(args.max_add, 1)

    summary = run_discovery(args)
    print_summary(summary)
    if args.digest and not args.dry_run:
        try:
            send_digest(summary)
        except Exception as e:
            print(f"[warn] digest failed: {e}")


if __name__ == "__main__":
    main()
